/** Slices a verbatim span of `text` between the start and (exclusive) end markers. */
export function sliceDuaRange(text: string | null, range?: DuaRange): string | null {
  if (!text || !range) return null;
  const body = text.replace(/\s+/g, " ").trim();
  const start = locateIndex(body, range[0]);
  if (start === -1) return null;
  let to = body.length;
  if (range[1]) {
    const end = locateIndex(body.slice(start + range[0].length), range[1]);
    if (end !== -1) to = start + range[0].length + end;
  }
  const out = body.slice(start, to).replace(/[«»“”]/g, "").replace(/\s+/g, " ").trim();
  return out || null;
}
